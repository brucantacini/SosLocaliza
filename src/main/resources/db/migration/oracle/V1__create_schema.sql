CREATE TABLE T_SOS_EVENTO (
    ID_EVENTO NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_EVENTO VARCHAR2(100 CHAR) NOT NULL,
    DESCRICAO_EVENTO VARCHAR2(500 CHAR),
    CAUSAS VARCHAR2(300 CHAR),
    ALERTAS VARCHAR2(300 CHAR),
    ACOES_ANTES VARCHAR2(500 CHAR),
    ACOES_DURANTE VARCHAR2(500 CHAR),
    ACOES_DEPOIS VARCHAR2(500 CHAR),
    DATA_CRIACAO TIMESTAMP,
    DATA_ATUALIZACAO TIMESTAMP,
    ATIVO NUMBER(1) DEFAULT 1
);

CREATE TABLE T_SOS_SMS (
    ID_SMS NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REMETENTE VARCHAR2(100 CHAR) NOT NULL,
    NUMERO_TELEFONE VARCHAR2(20 CHAR) NOT NULL,
    MENSAGEM VARCHAR2(1000 CHAR) NOT NULL,
    DATA_ENVIO TIMESTAMP,
    ENVIADO_COM_SUCESSO NUMBER(1) DEFAULT 0,
    ERRO VARCHAR2(500 CHAR),
    DDD VARCHAR2(3 CHAR),
    ID_EVENTO NUMBER(19),
    CONSTRAINT FK_SMS_EVENTO FOREIGN KEY (ID_EVENTO) REFERENCES T_SOS_EVENTO (ID_EVENTO)
);

CREATE TABLE T_SOS_APP_USER (
    ID_USER NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(100 CHAR) NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    ROLE VARCHAR2(50 CHAR) NOT NULL
);
