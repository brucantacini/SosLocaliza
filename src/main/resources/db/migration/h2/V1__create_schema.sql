CREATE TABLE T_SOS_EVENTO (
    ID_EVENTO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_EVENTO VARCHAR(100) NOT NULL,
    DESCRICAO_EVENTO VARCHAR(500),
    CAUSAS VARCHAR(300),
    ALERTAS VARCHAR(300),
    ACOES_ANTES VARCHAR(500),
    ACOES_DURANTE VARCHAR(500),
    ACOES_DEPOIS VARCHAR(500),
    DATA_CRIACAO TIMESTAMP,
    DATA_ATUALIZACAO TIMESTAMP,
    ATIVO BOOLEAN DEFAULT TRUE
);

CREATE TABLE T_SOS_SMS (
    ID_SMS BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REMETENTE VARCHAR(100) NOT NULL,
    NUMERO_TELEFONE VARCHAR(20) NOT NULL,
    MENSAGEM VARCHAR(1000) NOT NULL,
    DATA_ENVIO TIMESTAMP,
    ENVIADO_COM_SUCESSO BOOLEAN DEFAULT FALSE,
    ERRO VARCHAR(500),
    DDD VARCHAR(3),
    ID_EVENTO BIGINT,
    CONSTRAINT FK_SMS_EVENTO FOREIGN KEY (ID_EVENTO) REFERENCES T_SOS_EVENTO (ID_EVENTO)
);

CREATE TABLE T_SOS_APP_USER (
    ID_USER BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR(100) NOT NULL,
    ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
    ROLE VARCHAR(50) NOT NULL
);
